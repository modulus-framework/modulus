-- Upgrade for existing PostgreSQL deployments, IDENTITY database: the account lifecycle, principal kind, ERP identifiers and the
-- lifecycle history of 2026-10 (VER-2).
--
-- Run as the schema owner, once, before the new release starts. The user table is the application's identity user table (ASP.NET
-- Identity's default is AspNetUsers):
--   psql "$IDENTITY_CONNECTION" -v ON_ERROR_STOP=1 -v user_table=AspNetUsers -f identity-platform-2026-10.identity.postgresql.sql
--
-- Accounts disabled through IsActive = false are carried over to the Disabled lifecycle state, so they stay disabled. The index names
-- follow EF's convention for AspNetUsers; a renamed user table keeps working with differently named indexes.
-- Idempotent: a second run changes nothing, also after the new release has changed accounts. Existing deployments only.

BEGIN;

ALTER TABLE :"user_table" ADD COLUMN IF NOT EXISTS "PrincipalKind" varchar(32) NOT NULL DEFAULT 'person';
ALTER TABLE :"user_table" ADD COLUMN IF NOT EXISTS "Lifecycle" varchar(32) NOT NULL DEFAULT 'Active';
ALTER TABLE :"user_table" ADD COLUMN IF NOT EXISTS "LifecycleChangedAt" timestamptz NULL;
ALTER TABLE :"user_table" ADD COLUMN IF NOT EXISTS "SuspensionReason" varchar(64) NULL;
ALTER TABLE :"user_table" ADD COLUMN IF NOT EXISTS "SuspensionNote" varchar(512) NULL;
ALTER TABLE :"user_table" ADD COLUMN IF NOT EXISTS "MustChangePin" boolean NOT NULL DEFAULT false;
ALTER TABLE :"user_table" ADD COLUMN IF NOT EXISTS "EmployeeCode" text NULL;
ALTER TABLE :"user_table" ADD COLUMN IF NOT EXISTS "PinHash" text NULL;
ALTER TABLE :"user_table" ADD COLUMN IF NOT EXISTS "ExternalId" text NULL;

-- The lifecycle replaces IsActive: a disabled account must stay disabled after the upgrade. Only accounts whose lifecycle has never been
-- changed are carried over, so a rerun cannot disable an account that the new release has since re-enabled.
UPDATE :"user_table" SET "Lifecycle" = 'Disabled'
WHERE "IsActive" = false AND "Lifecycle" = 'Active' AND "LifecycleChangedAt" IS NULL;

CREATE INDEX IF NOT EXISTS "IX_AspNetUsers_TenantId_EmployeeCode" ON :"user_table" ("TenantId", "EmployeeCode");
CREATE INDEX IF NOT EXISTS "IX_AspNetUsers_TenantId_ExternalId" ON :"user_table" ("TenantId", "ExternalId");

-- Lifecycle history: append-only, without a foreign key so it outlives the account.
CREATE TABLE IF NOT EXISTS "ModulusAccountTransitions" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
    "UserId" uuid NOT NULL,
    "FromState" varchar(32) NOT NULL,
    "ToState" varchar(32) NOT NULL,
    "ActorId" uuid NULL,
    "Reason" varchar(512) NULL,
    "OccurredAt" timestamptz NOT NULL,
    CONSTRAINT "PK_ModulusAccountTransitions" PRIMARY KEY ("Id")
);
CREATE INDEX IF NOT EXISTS "IX_ModulusAccountTransitions_UserId_Id" ON "ModulusAccountTransitions" ("UserId", "Id");

COMMIT;
